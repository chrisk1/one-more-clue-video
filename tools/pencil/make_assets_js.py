#!/usr/bin/env python3
"""Regenerate src/assets_pencil.js from assets/pencil/. Run from the project root.

film.html loads it after src/assets.js: each pencil drawing replaces the ink original with the same name, boil variants
(<name>~1, <name>~2) are added alongside, and the two texture swatches are added as 'tex_hatch' and 'tex_soft'."""
import json, os

D = 'assets/pencil'
M = {f[:-5]: f'../{D}/{f}' for f in sorted(os.listdir(D)) if f.endswith('.webp') and not f.startswith('_')}
for t in ('hatch', 'soft'): M[f'tex_{t}'] = f'../{D}/texture/{t}.webp'
open('src/assets_pencil.js', 'w').write('// Generated by tools/pencil/make_assets_js.py: coloured-pencil drawings that replace the ink '
                                        'originals by name.\nwindow.P4_ASSETS = ' + json.dumps(M, indent=0, ensure_ascii=False) + ';\n')
print(len(M), 'entries')
