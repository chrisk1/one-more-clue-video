#!/usr/bin/env python3
"""Regenerate src/assets.js (sprite/plate name -> image path) from the files in assets/.

    python3 tools/make_assets_js.py          # run from the project root

Naming rules (the name is what the shot code passes to spr()/plate()):
  assets/sprites/*.png            prop_<x>.png -> "<x>", everything else -> file stem
  assets/sprites/<group>/*.png    file stem (windows/, typing/, ...)
  assets/sets/*.png               set_<x>.png -> "<x>", paper_cream.png -> "paper"
assets/ref/ holds the character reference sheets used when generating new art; it is not loaded by the film.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def pngs(rel):
    d = os.path.join(ROOT, rel)
    return sorted(f for f in os.listdir(d) if f.endswith('.png') and os.path.isfile(os.path.join(d, f)))


def main():
    out = []
    for f in pngs('assets/sprites'):
        n = f[:-4]
        out.append((n[5:] if n.startswith('prop_') else n, 'assets/sprites/' + f))
    sub = os.path.join(ROOT, 'assets/sprites')
    for g in sorted(d for d in os.listdir(sub) if os.path.isdir(os.path.join(sub, d))):
        out += [(f[:-4], f'assets/sprites/{g}/{f}') for f in pngs(f'assets/sprites/{g}')]
    for f in pngs('assets/sets'):
        n = f[:-4]
        out.append(('paper' if n == 'paper_cream' else n[4:] if n.startswith('set_') else n, 'assets/sets/' + f))
    names = [n for n, _ in out]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        raise SystemExit(f'duplicate asset names: {sorted(dup)}')
    body = ''.join(f"  ['{n}', '../{p}'],\n" for n, p in out)
    js = ('// Generated by tools/make_assets_js.py: sprite/plate name -> image path (relative to src/film.html).\n'
          'const ASSET_LIST = [\n' + body + '];\nwindow.ASSET_LIST = ASSET_LIST;\n')
    with open(os.path.join(ROOT, 'src/assets.js'), 'w') as fh:
        fh.write(js)
    print(len(out), 'assets -> src/assets.js')


if __name__ == '__main__':
    main()
